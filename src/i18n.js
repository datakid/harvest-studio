const dicts = { en };
let lang = 'en';

let pending = null;
const loadAr = () => (pending ||= import('/ar.js').then((m) => (dicts.ar = m.default)).catch(() => { pending = null; }));
export const warmLang = loadAr;

export const setLang = async (value) => {
  if (value === 'ar') await loadAr();
  lang = dicts[value] ? value : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
};
export const getLang = () => lang;
export const t = (key, vars) => {
  const raw = dicts[lang][key] ?? en[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '' : vars[k])) : raw;
};
export const keys = Object.keys(en);
export const dictionaries = dicts;
